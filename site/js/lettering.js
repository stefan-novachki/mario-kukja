// Measure a string in glyph units (multiply by size/6 for paper units).
export function textWidth(str, tracking = 0.9) {
  let w = 0;
  for (const ch of normal(str)) {
    const g = GLYPHS[ch] || GLYPHS[' '];
    w += g[0] + tracking;
  }
  return Math.max(0, w - tracking);
}

function normal(str) {
  return [...String(str)].map((c) => {
    if (GLYPHS[c]) return c;
    const up = c.toUpperCase();
    return GLYPHS[up] ? up : ' ';
  });
}

// Returns polylines in paper units, y down (SVG), for text whose baseline starts at (x, y).
// align: 'start' | 'middle' | 'end'. size = cap height in paper units.
export function textStrokes(str, x, y, size, { align = 'start', tracking = 0.9, slant = 0.08 } = {}) {
  const k = size / 6;
  const w = textWidth(str, tracking) * k;
  let cx = align === 'middle' ? x - w / 2 : align === 'end' ? x - w : x;
  const lines = [];
  for (const ch of normal(str)) {
    const [adv, strokes] = GLYPHS[ch] || GLYPHS[' '];
    for (const s of strokes) {
      lines.push(s.map(([gx, gy]) => [cx + (gx + gy * slant) * k, y - gy * k]));
    }
    cx += (adv + tracking) * k;
  }
  return { lines, width: w };
}
