// Single-stroke architect's lettering (caps), drawn as pencil strokes rather than a font file.
// Glyph grid: cap height 6, baseline 0, y up. Each glyph = [advance, strokes[]].

const ellipse = (cx, cy, rx, ry, a0 = 0, a1 = Math.PI * 2, n = 18) => {
  const p = [];
  for (let i = 0; i <= n; i++) {
    const a = a0 + (a1 - a0) * (i / n);
    p.push([cx + Math.cos(a) * rx, cy + Math.sin(a) * ry]);
  }
  return p;
};

